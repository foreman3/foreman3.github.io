// Sync the flyout and offline inventory before publishing menu or game changes.
// node scripts/build-offline.cjs [--check]
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const list = fs.readFileSync(path.join(root, 'Games.md'), 'utf8');
const sections = list.split(/^## /m).slice(1).map(section => ({
  title: section.split(/\r?\n/, 1)[0],
  entries: [...section.matchAll(/^- \[([^\]]+)\]\(([a-z0-9-]+\/|https:\/\/[^)\s]+)\)/gm)]
    .map(([, title, href]) => ({ title, href }))
}));
const games = sections.flatMap(section => section.entries)
  .map(entry => entry.href)
  .filter(href => !href.startsWith('https://'))
  .map(href => href.slice(0, -1));

const check = process.argv.includes('--check');
function writeGenerated(name, content) {
  const target = path.join(root, name);
  if (!check) {
    fs.writeFileSync(target, content);
  } else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== content) {
    console.error(`${name} is stale. Run node scripts/build-offline.cjs before publishing.`);
    process.exitCode = 1;
  }
}

const entities = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' };
const escapeHTML = value => value.replace(/[&<>"]/g, character => entities[character]);
const menu = sections.map(({ title, entries }) => {
  const links = entries.map(({ title, href }) => {
    const url = href.startsWith('https://') ? href : `../${href}`;
    return `    <li><a href="${escapeHTML(url)}">${escapeHTML(title)}</a></li>`;
  });
  return [`  <h3>${escapeHTML(title)}</h3>`, '  <ul>', ...links, '  </ul>'].join('\n');
}).join('\n');
const sidebar = `<!-- Generated from Games.md by scripts/build-offline.cjs. -->
<nav id="sidebar">
  <a class="sidebar-logo" href="../index.html" aria-label="Return to the Vibecade main menu">
    <img src="../images/vibecade.svg" alt="VibeCade" />
  </a>
${menu}
</nav>
`;

const files = new Set(['index.html', 'offline.html', 'pwa.js', 'manifest.webmanifest', 'flyout.js', 'flyout.css', 'mobile-fullscreen.js', 'sidebar.html', 'sidebar.css']);
const runtime = /\.(?:html|js|css|svg|png|jpe?g|webp|gif|ico|json|woff2?|ttf|ogg|mp3|wav)$/i;
function collect(directory) {
  for (const entry of fs.readdirSync(path.join(root, directory), { withFileTypes: true })) {
    const name = `${directory}/${entry.name}`;
    if (entry.isDirectory()) {
      if (!/^(?:video_frames|screenshots|node_modules|tests)$/.test(entry.name)) collect(name);
    } else if (runtime.test(name) && !/(?:^|\/)(?:verify|test)[-.]|headless|contact\.png$|frame_\d+\.png$/.test(name)) {
      files.add(name);
    }
  }
}
for (const directory of [...new Set(games), 'images', 'vendor']) collect(directory);
const assets = [...files].sort();
const hash = crypto.createHash('sha256');
let bytes = 0;
for (const asset of assets) {
  let data = asset === 'sidebar.html' ? Buffer.from(sidebar) : fs.readFileSync(path.join(root, asset));
  // Git may check text files out as CRLF on Windows and LF on the host.
  if (/\.(?:html|js|css|svg|json|webmanifest)$/.test(asset)) data = Buffer.from(data.toString('utf8').replace(/\r\n/g, '\n'));
  hash.update(asset).update('\0').update(data);
  bytes += data.length;
}
const content = '// Generated by scripts/build-offline.cjs. Do not edit by hand.\nself.VIBECADE_OFFLINE = ' + JSON.stringify({ version: hash.digest('hex').slice(0, 16), games: games.length, bytes, assets }, null, 2) + ';\n';
writeGenerated('sidebar.html', sidebar);
writeGenerated('offline-assets.js', content);
console.log(`${games.length} games, ${assets.length} files, ${(bytes / 1024 / 1024).toFixed(1)} MiB offline`);
